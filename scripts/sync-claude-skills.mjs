import { readdir, readFile, mkdir, writeFile, lstat } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { pathToFileURL } from 'node:url'

export function adapter(name, source) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) throw new Error(`Invalid skill directory: ${name}`)
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)
  if (!match || !new RegExp(`^name: ${name}$`, 'm').test(match[1]) || !/^description: .+/m.test(match[1])) throw new Error(`Expected matching name and description frontmatter in ${name}`)
  return `---\n${match[1].replaceAll('\r', '')}\n---\n\n<!-- Generated by scripts/sync-claude-skills.mjs; edit the canonical skill. -->\n\nRead and follow \`.agents/skills/${name}/SKILL.md\` from the repository root before doing this task. That file is the canonical procedure; this adapter only enables Claude discovery.\n\nResolve relative references, scripts and assets from \`.agents/skills/${name}/\`, not this adapter directory. Follow root \`AGENTS.md\` for branch, versioning, permissions and handoff rules.\n`
}

async function regular(path, directory) {
  let stat
  try { stat = await lstat(path) } catch (error) { if (error.code === 'ENOENT') return; throw error }
  if (stat.isSymbolicLink() || (directory ? !stat.isDirectory() : !stat.isFile())) throw new Error(`Refusing non-regular adapter path: ${path}`)
}

export async function sync(root, write = false) {
  const sourceRoot = join(root, '.agents/skills'), targetRoot = join(root, '.claude/skills')
  await regular(join(root, '.claude'), true)
  await regular(targetRoot, true)
  const names = (await readdir(sourceRoot, { withFileTypes: true })).filter(d => d.isDirectory()).map(d => d.name).sort()
  const expected = new Map()
  for (const name of names) expected.set(name, adapter(name, await readFile(join(sourceRoot, name, 'SKILL.md'), 'utf8')))
  let existing = []
  try { existing = await readdir(targetRoot, { withFileTypes: true }) } catch (error) { if (error.code !== 'ENOENT') throw error }
  for (const entry of existing) {
    if (!expected.has(entry.name)) throw new Error(`Unmapped Claude skill: ${entry.name}; review and remove obsolete adapters manually`)
    if (!entry.isDirectory()) throw new Error(`Expected regular skill directory: ${entry.name}`)
  }
  const stale = []
  for (const [name, content] of expected) {
    const path = join(targetRoot, name, 'SKILL.md')
    await regular(join(targetRoot, name), true)
    await regular(path, false)
    let current
    try { current = await readFile(path, 'utf8') } catch (error) { if (error.code !== 'ENOENT') throw error }
    if (current?.replaceAll('\r\n', '\n') === content) continue
    if (!write) { stale.push(name); continue }
    if (current && !current.includes('<!-- Generated by scripts/sync-claude-skills.mjs;')) throw new Error(`Refusing to overwrite custom skill: ${name}`)
    await mkdir(join(targetRoot, name), { recursive: true })
    await writeFile(path, content)
  }
  if (stale.length) throw new Error(`Missing/stale Claude adapters: ${stale.join(', ')}. Run node scripts/sync-claude-skills.mjs --write`)
  return names.length
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2)
  if (args.some(a => a !== '--write')) throw new Error('Usage: node scripts/sync-claude-skills.mjs [--write]')
  console.log(`Claude skill adapters valid: ${await sync(resolve('.'), args.includes('--write'))}`)
}
